// Command spvariables writes the `.jx/variables.sh` file the catalogue's steps source.
//
// It is the replacement for `jx gitops variables`, and it reads the environment and the
// checkout only: no cluster, no JX CRDs. The file path and the export names are unchanged,
// because 48 repos source it.
package main

import (
	"flag"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
)

// input is everything vars() needs. It is a struct rather than reads of os.Getenv so the
// rules can be tested without a checkout or a pipeline.
type input struct {
	Owner, Repo, GitBranch              string
	PullNumber, BuildNumber, Version    string
	Registry, RegistryOrg, PushRegistry string
	KanikoFlags, Domain, SubDomain      string
	ChartRepository                     string
	JenkinsXURL                         string
	ClusterID                           string
	HasPreviewDockerfile                bool
}

type pair struct{ Name, Value string }

// vars applies the derivation rules and returns the exports, in the order a file gets them.
//
// An empty value is left out of the file, so a step that sources it finds the variable unset.
func vars(in input) []pair {
	out := make([]pair, 0, 20)
	pr := in.PullNumber != ""

	branch := in.GitBranch
	if pr {
		branch = "PR-" + in.PullNumber
	}

	version := in.Version
	if version == "" && pr {
		version = fmt.Sprintf("0.0.0-PR-%s-%s-SNAPSHOT", in.PullNumber, in.BuildNumber)
	}

	dockerfile := "Dockerfile"
	if pr && in.HasPreviewDockerfile {
		dockerfile = "Dockerfile-preview"
	}

	kind := "feature"
	switch {
	case pr:
		kind = "pullrequest"
	case in.GitBranch == "main" || in.GitBranch == "master":
		kind = "release"
	}

	push := in.PushRegistry
	if push == "" {
		push = in.Registry
	}
	chartRepo := in.ChartRepository
	if chartRepo == "" && in.Registry != "" && in.RegistryOrg != "" {
		chartRepo = in.Registry + "/" + in.RegistryOrg + "-charts"
	}
	repoName := strings.ReplaceAll(strings.ToLower(in.Repo), "/", "-")

	mink := ""
	if version != "" && in.Registry != "" && in.RegistryOrg != "" && repoName != "" {
		mink = strings.Join([]string{in.Registry, in.RegistryOrg, repoName}, "/") + ":" + version
	}

	add := func(name, value string) {
		if value != "" {
			out = append(out, pair{name, value})
		}
	}
	add("APP_NAME", in.Repo)
	add("CLUSTER_ID", in.ClusterID)
	add("BRANCH_NAME", branch)
	add("BUILD_NUMBER", in.BuildNumber)
	add("DOCKERFILE_PATH", dockerfile)
	add("DOCKER_REGISTRY", in.Registry)
	add("DOCKER_REGISTRY_ORG", in.RegistryOrg)
	add("DOMAIN", in.Domain)
	add("GIT_BRANCH", in.GitBranch)
	add("JENKINS_X_URL", in.JenkinsXURL)
	add("JX_CHART_REPOSITORY", chartRepo)
	add("KANIKO_FLAGS", in.KanikoFlags)
	add("MINK_AS", "tekton-bot")
	add("MINK_IMAGE", mink)
	add("NAMESPACE_SUB_DOMAIN", in.SubDomain)
	add("PIPELINE_KIND", kind)
	add("PUSH_CONTAINER_REGISTRY", push)
	add("REPO_NAME", repoName)
	add("REPO_OWNER", in.Owner)
	add("VERSION", version)

	sort.Slice(out, func(i, j int) bool { return out[i].Name < out[j].Name })
	return out
}

func render(vs []pair) string {
	var b strings.Builder
	b.WriteString("# generated by: sp-variables\n")
	for _, v := range vs {
		fmt.Fprintf(&b, "export %s='%s'\n", v.Name, v.Value)
	}
	return b.String()
}

func envDefault(name, fallback string) string {
	if v := os.Getenv(name); v != "" {
		return v
	}
	return fallback
}

// git runs one git command in dir and returns its trimmed stdout, or "" if it fails. A
// missing git or a non-checkout is not this tool's error to raise, and "" reads as unknown:
// the caller then takes the value from a flag or omits the variable.
func git(dir string, args ...string) string {
	cmd := exec.Command("git", args...)
	cmd.Dir = dir
	out, err := cmd.Output()
	if err != nil {
		return ""
	}
	return strings.TrimSpace(string(out))
}

// ownerRepoFromGit reads the owner and repository out of the origin remote.
func ownerRepoFromGit(dir string) (string, string) {
	url := git(dir, "config", "--get", "remote.origin.url")
	if url == "" {
		return "", ""
	}
	url = strings.TrimSuffix(url, ".git")
	url = strings.TrimPrefix(url, "git@github.com:")
	url = strings.TrimPrefix(url, "https://github.com/")
	if i := strings.LastIndex(url, ":"); i >= 0 && !strings.Contains(url, "/") {
		url = url[i+1:]
	}
	parts := strings.Split(url, "/")
	if len(parts) < 2 {
		return "", ""
	}
	return parts[len(parts)-2], parts[len(parts)-1]
}

// clusterConfig reads the one ConfigMap that says what this cluster is. It is the only
// place in the catalogue that reads it: every task used to re-declare the key as a
// configMapKeyRef, and a value that is absent then reads as a default rather than as an
// error -- which is how a second cluster can quietly present itself as `gcp`.
//
// kubectl rather than client-go, for the reason go/e2e/cluster.go gives: every task image
// already carries kubectl, so this needs no kubeconfig plumbing, no generated API types and
// no RBAC beyond what the step already has.
//
// Two sources, in order, because the chart that should own all of this does not carry every
// key yet: jx-cluster-config (ours), then jenkins-x-docker-registry (JX boot's). When the
// chart carries them all, the second entry is a line to delete.
type clusterKey struct {
	name string
	cms  []string
	keys []string
}

var clusterKeys = []clusterKey{
	{"CLUSTER_ID", []string{"jx-cluster-config"}, []string{"CLUSTER_ID"}},
	{"DOCKER_REGISTRY", []string{"jx-cluster-config", "jenkins-x-docker-registry"}, []string{"DOCKER_REGISTRY", "docker.registry"}},
	{"DOCKER_REGISTRY_ORG", []string{"jx-cluster-config", "jenkins-x-docker-registry"}, []string{"DOCKER_REGISTRY_ORG", "docker.registry.org"}},
	{"PUSH_CONTAINER_REGISTRY", []string{"jx-cluster-config"}, []string{"PUSH_CONTAINER_REGISTRY"}},
	{"KANIKO_FLAGS", []string{"jx-cluster-config", "jenkins-x-docker-registry"}, []string{"KANIKO_FLAGS", "kaniko.flags"}},
	{"DOMAIN", []string{"jx-cluster-config"}, []string{"DOMAIN"}},
	{"NAMESPACE_SUB_DOMAIN", []string{"jx-cluster-config"}, []string{"NAMESPACE_SUB_DOMAIN"}},
}

// configMapValue returns one key's value, or "" when the ConfigMap or kubectl is absent. A
// missing cluster is not this tool's error: it also runs in a self-test and on a laptop.
func configMapValue(namespace, cm, key string) string {
	path := "{.data." + strings.ReplaceAll(key, ".", `\.`) + "}"
	out, err := exec.Command("kubectl", "-n", namespace, "get", "configmap", cm,
		"-o", "jsonpath="+path).Output()
	if err != nil {
		return ""
	}
	return strings.TrimSpace(string(out))
}

// clusterValues resolves every key from the environment first, then the ConfigMaps. The
// environment wins so a step can override one value without a new ConfigMap, and so the
// rules above are testable without a cluster.
func clusterValues(namespace string) map[string]string {
	out := make(map[string]string, len(clusterKeys))
	for _, ck := range clusterKeys {
		v := os.Getenv(ck.name)
		if v == "" && namespace != "" {
			for i, cm := range ck.cms {
				if i < len(ck.keys) {
					if v = configMapValue(namespace, cm, ck.keys[i]); v != "" {
						break
					}
				}
			}
		}
		if v != "" {
			out[ck.name] = v
		}
	}
	return out
}

func main() {
	var (
		dir         = flag.String("dir", ".", "the checkout to write into")
		file        = flag.String("file", filepath.Join(".jx", "variables.sh"), "the file to write, relative to -dir")
		owner       = flag.String("owner", "", "repository owner (default $REPO_OWNER, then the origin remote)")
		repo        = flag.String("repo", "", "repository name (default $REPO_NAME, then the origin remote)")
		branch      = flag.String("branch", "", "git branch (default: the checkout's HEAD branch)")
		pullNumber  = flag.String("pull-number", "", "pull request number (default $PULL_NUMBER)")
		buildNumber = flag.String("build-number", "", "build number (default $BUILD_NUMBER, then $BUILD_ID)")
		version     = flag.String("version", "", "version (default $VERSION, then the VERSION file, then a derived tag)")
		toStdout    = flag.Bool("print", false, "write to stdout instead of the file")
		require     = flag.String("require", "", "comma-separated variables that must be non-empty; exit 1 if any is not")
		namespace   = flag.String("namespace", "jx", "namespace holding the cluster ConfigMaps")
		noCluster   = flag.Bool("no-cluster", false, "use the environment only; never read the cluster")
	)
	flag.Parse()

	ns := ""
	if !*noCluster {
		ns = *namespace
	}
	cluster := clusterValues(ns)

	in := input{
		Owner:           first(*owner, os.Getenv("REPO_OWNER")),
		Repo:            first(*repo, os.Getenv("REPO_NAME")),
		GitBranch:       resolveBranch(*branch, os.Getenv("PULL_BASE_REF"), *dir),
		PullNumber:      first(*pullNumber, os.Getenv("PULL_NUMBER")),
		BuildNumber:     resolveBuildNumber(*buildNumber, os.Getenv),
		Registry:        cluster["DOCKER_REGISTRY"],
		RegistryOrg:     cluster["DOCKER_REGISTRY_ORG"],
		PushRegistry:    cluster["PUSH_CONTAINER_REGISTRY"],
		KanikoFlags:     cluster["KANIKO_FLAGS"],
		Domain:          cluster["DOMAIN"],
		SubDomain:       cluster["NAMESPACE_SUB_DOMAIN"],
		ChartRepository: os.Getenv("JX_CHART_REPOSITORY"),
		JenkinsXURL:     os.Getenv("JENKINS_X_URL"),
		ClusterID:       cluster["CLUSTER_ID"],
	}
	if in.Owner == "" || in.Repo == "" {
		o, r := ownerRepoFromGit(*dir)
		if in.Owner == "" {
			in.Owner = o
		}
		if in.Repo == "" {
			in.Repo = r
		}
	}
	if *version != "" {
		in.Version = *version
	} else if v := os.Getenv("VERSION"); v != "" {
		in.Version = v
	} else if b, err := os.ReadFile(filepath.Join(*dir, "VERSION")); err == nil {
		in.Version = strings.TrimSpace(string(b))
	}
	if _, err := os.Stat(filepath.Join(*dir, "Dockerfile-preview")); err == nil {
		in.HasPreviewDockerfile = true
	}

	// A pull request with no build number produces a tag that is not unique to the run, so
	// two runs on one PR overwrite each other's image and the second preview is the first
	// build's. Refusing here is the only place the mistake is visible.
	if in.PullNumber != "" && in.BuildNumber == "" {
		fmt.Fprintln(os.Stderr, "FAIL: PULL_NUMBER is set but BUILD_NUMBER is not — the image tag would "+
			"not identify this run (see -build-number, $BUILD_NUMBER, $BUILD_ID).")
		os.Exit(1)
	}

	// A release with no version is a release with no version. jx writes one anyway, as
	// `MINK_IMAGE='…:'` with a trailing colon and no VERSION at all; the version step is
	// supposed to have written the VERSION file before this runs, so refusing names the
	// missing step instead of hiding it.
	// A release with no VERSION file: derive it from the cluster's release tags, the same rule
	// the release tasks use. Some release tasks run in their OWN pod (openapi-generation is a
	// separate PipelineRun), so the VERSION file next-version wrote in the service's
	// from-build-pack pod is not in their checkout.
	if in.PullNumber == "" && in.Version == "" {
		in.Version = versionFromTag(*dir, in.ClusterID)
		if in.Version == "" {
			pattern := "v*"
			if in.ClusterID != "" {
				pattern = "v*-" + in.ClusterID
			}
			fmt.Fprintf(os.Stderr, "note: no VERSION file and no %s tag; VERSION and MINK_IMAGE "+
				"are omitted from .jx/variables.sh\n", pattern)
		}
	}

	vs := vars(in)
	missing := missingRequired(vs, *require)
	if len(missing) > 0 {
		fmt.Fprintf(os.Stderr, "FAIL: required variable(s) empty: %s\n", strings.Join(missing, ", "))
		os.Exit(1)
	}

	body := render(vs)
	if *toStdout {
		fmt.Print(body)
		return
	}
	path := filepath.Join(*dir, *file)
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		fmt.Fprintf(os.Stderr, "FAIL: %v\n", err)
		os.Exit(1)
	}
	if err := os.WriteFile(path, []byte(body), 0o644); err != nil {
		fmt.Fprintf(os.Stderr, "FAIL: %v\n", err)
		os.Exit(1)
	}
	fmt.Printf("==> sp-variables: wrote %s (%d exports)\n", path, len(vs))
}

// missingRequired reports the variables named in want that the file does not set. Steps
// branch on these (a preview URL, a registry), and an absent one reads as "not applicable"
// rather than "not configured".
func missingRequired(vs []pair, want string) []string {
	if strings.TrimSpace(want) == "" {
		return nil
	}
	set := make(map[string]bool, len(vs))
	for _, v := range vs {
		set[v.Name] = true
	}
	var missing []string
	for _, name := range strings.Split(want, ",") {
		name = strings.TrimSpace(name)
		if name != "" && !set[name] {
			missing = append(missing, name)
		}
	}
	return missing
}

// resolveBranch resolves the branch the build is FOR. A PR checkout is detached at the merge
// SHA, so `git rev-parse --abbrev-ref HEAD` answers "HEAD" -- a value that would make every
// pull request look like a feature branch on a branch called HEAD. PULL_BASE_REF is what
// Lighthouse actually knows (the target branch), so it is consulted first.
func resolveBranch(flagValue, baseRef, dir string) string {
	if flagValue != "" {
		return flagValue
	}
	if baseRef != "" {
		return baseRef
	}
	if b := git(dir, "rev-parse", "--abbrev-ref", "HEAD"); b != "HEAD" {
		return b
	}
	return ""
}

// plainVersion matches a release version with no cluster suffix.
var plainVersion = regexp.MustCompile(`^[0-9]+\.[0-9]+\.[0-9]+$`)

// versionFromTag derives a version from the newest release tag for this cluster.
//
// The tag pattern is the estate's: `v<version>-<CLUSTER_ID>` when a cluster suffix is set, `v<ver>`
// otherwise. `--sort=-v:refname` is a VERSION sort, not a lexical one — v0.10.0 after v0.9.9.
//
// proven-by: TestVersionFromTag_StripsTheVPrefixAndClusterSuffix
func versionFromTag(dir, clusterID string) string {
	pattern := "v*"
	if clusterID != "" {
		pattern = "v*-" + clusterID
	}
	out := git(dir, "tag", "-l", pattern, "--sort=-v:refname")
	if out == "" {
		return ""
	}
	// With no cluster suffix only a PLAIN semver tag counts: `v*` also matches
	// `v0.10.1-az`, and taking that would publish another cluster's version as this one's.
	// proven-by: TestVersionFromTag_StripsTheVPrefixAndClusterSuffix
	for _, line := range strings.Split(strings.TrimSpace(out), "\n") {
		v := strings.TrimPrefix(strings.TrimSpace(line), "v")
		if clusterID != "" {
			if !strings.HasSuffix(v, "-"+clusterID) {
				continue
			}
			return strings.TrimSuffix(v, "-"+clusterID)
		}
		if plainVersion.MatchString(v) {
			return v
		}
	}
	return ""
}

// resolveBuildNumber resolves the run identifier. Lighthouse sets BUILD_ID (the millisecond
// value in its buildNum label) and not BUILD_NUMBER, so the fallback is what makes this work
// in a real presubmit.
// proven-by: TestBuildNumber_FallsBackToTheLighthouseBuildID
func resolveBuildNumber(flagValue string, getenv func(string) string) string {
	return first(flagValue, getenv("BUILD_NUMBER"), getenv("BUILD_ID"))
}

func first(vals ...string) string {
	for _, v := range vals {
		if v != "" {
			return v
		}
	}
	return ""
}
