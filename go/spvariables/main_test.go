package main

import (
	"strings"
	"testing"
)

func env(vs []pair) map[string]string {
	m := make(map[string]string, len(vs))
	for _, v := range vs {
		m[v.Name] = v.Value
	}
	return m
}

var goldens = input{
	Owner: "mikelear", Repo: "leartech-bus-common", GitBranch: "main",
	PullNumber: "42", BuildNumber: "7",
	Registry: "us-central1-docker.pkg.dev/product-first", RegistryOrg: "oci",
	KanikoFlags: "--skip-unused-stages", Domain: "jx.leartech.com",
}

// The tag identifies the run. Two runs on one PR must not produce the same one, or the
// second preview build silently overwrites the first.
//
// proven-by: TestPullRequest_TagIdentifiesTheRun
func TestPullRequest_TagIdentifiesTheRun(t *testing.T) {
	got := env(vars(goldens))
	if want := "0.0.0-PR-42-7-SNAPSHOT"; got["VERSION"] != want {
		t.Errorf("VERSION = %q, want %q", got["VERSION"], want)
	}
	if got["PIPELINE_KIND"] != "pullrequest" {
		t.Errorf("PIPELINE_KIND = %q", got["PIPELINE_KIND"])
	}
	// The checkout is the base branch, so the branch NAME has to come from the PR number.
	if got["BRANCH_NAME"] != "PR-42" {
		t.Errorf("BRANCH_NAME = %q, want PR-42", got["BRANCH_NAME"])
	}
	if got["GIT_BRANCH"] != "main" {
		t.Errorf("GIT_BRANCH = %q, want the real branch", got["GIT_BRANCH"])
	}
}

// A VERSION file wins over the derived tag: the release pipeline writes it first, and the
// derived tag would replace a real version with a snapshot one.
//
// proven-by: TestVersionFile_WinsOverTheDerivedTag
func TestVersionFile_WinsOverTheDerivedTag(t *testing.T) {
	in := goldens
	in.Version = "0.23.1"
	got := env(vars(in))
	if got["VERSION"] != "0.23.1" {
		t.Errorf("VERSION = %q, want the VERSION file's value", got["VERSION"])
	}
	if got["MINK_IMAGE"] != "us-central1-docker.pkg.dev/product-first/oci/leartech-bus-common:0.23.1" {
		t.Errorf("MINK_IMAGE = %q", got["MINK_IMAGE"])
	}
}

// Lighthouse sets BUILD_ID and not BUILD_NUMBER, so a run that supplied only what Lighthouse
// gives must still produce a distinct tag.
//
// proven-by: TestBuildNumber_FallsBackToTheLighthouseBuildID
func TestBuildNumber_FallsBackToTheLighthouseBuildID(t *testing.T) {
	envs := map[string]string{"BUILD_ID": "1795516272883"}
	getenv := func(k string) string { return envs[k] }
	if got := resolveBuildNumber("", getenv); got != "1795516272883" {
		t.Errorf("buildNumber = %q, want the BUILD_ID", got)
	}
	if got := resolveBuildNumber("7", getenv); got != "7" {
		t.Errorf("buildNumber = %q, want the flag to win", got)
	}
}

// A PR checkout is detached, so git answers "HEAD". Taking it would make every pull request a
// feature build on a branch called HEAD, which changes PIPELINE_KIND and the version tag.
//
// proven-by: TestBranch_IgnoresTheDetachedHead
func TestBranch_IgnoresTheDetachedHead(t *testing.T) {
	if got := resolveBranch("", "main", t.TempDir()); got != "main" {
		t.Errorf("resolveBranch = %q, want PULL_BASE_REF", got)
	}
	if got := resolveBranch("release-1", "main", t.TempDir()); got != "release-1" {
		t.Errorf("resolveBranch = %q, want the flag to win", got)
	}
	if got := resolveBranch("", "", t.TempDir()); got != "" {
		t.Errorf("resolveBranch = %q in a directory that is not a checkout, want empty", got)
	}
}

func TestReleaseAndFeature_Kind(t *testing.T) {
	for branch, want := range map[string]string{"main": "release", "master": "release", "feat/x": "feature"} {
		in := goldens
		in.PullNumber, in.BuildNumber, in.GitBranch, in.Version = "", "", branch, "1.2.3"
		if got := env(vars(in))["PIPELINE_KIND"]; got != want {
			t.Errorf("branch %q: PIPELINE_KIND = %q, want %q", branch, got, want)
		}
	}
}

// An unset variable is absent, not present-and-empty: a step can test for unset, and an
// empty registry in a kaniko destination is a push to nowhere.
//
// proven-by: TestEmptyValues_AreOmittedNotEmpty
func TestEmptyValues_AreOmittedNotEmpty(t *testing.T) {
	in := goldens
	in.Registry, in.RegistryOrg, in.Domain = "", "", ""
	for _, v := range vars(in) {
		if v.Value == "" {
			t.Errorf("%s was emitted with an empty value", v.Name)
		}
	}
	if _, ok := env(vars(in))["DOCKER_REGISTRY"]; ok {
		t.Error("DOCKER_REGISTRY emitted although it has no source")
	}
}

func TestPreviewDockerfile_OnlyOnAPullRequest(t *testing.T) {
	in := goldens
	in.HasPreviewDockerfile = true
	if got := env(vars(in))["DOCKERFILE_PATH"]; got != "Dockerfile-preview" {
		t.Errorf("pull request: DOCKERFILE_PATH = %q, want Dockerfile-preview", got)
	}
	in.PullNumber = ""
	in.Version = "1.0.0"
	if got := env(vars(in))["DOCKERFILE_PATH"]; got != "Dockerfile" {
		t.Errorf("release: DOCKERFILE_PATH = %q, want Dockerfile", got)
	}
}

func TestChartRepository_IsRegistryOrgCharts(t *testing.T) {
	if got := env(vars(goldens))["JX_CHART_REPOSITORY"]; got != "us-central1-docker.pkg.dev/product-first/oci-charts" {
		t.Errorf("JX_CHART_REPOSITORY = %q", got)
	}
}

func TestRender_IsShellSourceable(t *testing.T) {
	body := render(vars(goldens))
	if !strings.HasPrefix(body, "# generated by: sp-variables\n") {
		t.Errorf("missing the generation marker, so a prose gate would count these lines: %q",
			strings.SplitN(body, "\n", 2)[0])
	}
	for _, line := range strings.Split(strings.TrimSpace(body), "\n")[1:] {
		if !strings.HasPrefix(line, "export ") || !strings.HasSuffix(line, "'") {
			t.Errorf("not an export line: %q", line)
		}
	}
}

func TestMissingRequired_NamesWhatIsAbsent(t *testing.T) {
	in := goldens
	in.Registry = ""
	in.RegistryOrg = ""
	got := missingRequired(vars(in), " VERSION, DOCKER_REGISTRY ,,DOCKER_REGISTRY_ORG")
	if strings.Join(got, ",") != "DOCKER_REGISTRY,DOCKER_REGISTRY_ORG" {
		t.Errorf("missingRequired = %v", got)
	}
	if len(missingRequired(vars(goldens), "VERSION,REPO_NAME")) != 0 {
		t.Error("reported a variable that is set")
	}
}
